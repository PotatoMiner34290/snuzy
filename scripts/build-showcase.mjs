// One-shot generator: parses public/midi/placeholder.mid and writes
// components/ShowcaseSong.ts so the song IS the instant startup state
// (no fetch, no loading flash). Re-run after swapping the MIDI:
//   npm run showcase
import { readFileSync, writeFileSync } from 'node:fs';
import pkg from '@tonejs/midi';
const { Midi } = pkg;

const STEPS_PER_BAR = 16;
const MAX_STEPS = 8192;
const BLOCK_STEPS = 64;

const CHANNEL_COLORS = [
  '#ff4b4b', '#ff8800', '#ffd000', '#00e676', '#00e5ff', '#00b0ff',
  '#651fff', '#d500f9', '#ff4081', '#f9a825', '#ab47bc', '#1de9b6'
];

const NOTE_NAMES = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B'];
const midiNoteName = (midi) => `${NOTE_NAMES[((midi % 12) + 12) % 12]}${Math.floor(midi / 12) - 1}`;

// Same GM names the app shows (parsed from the TS source so they can't drift).
const engineSrc = readFileSync(new URL('../components/SoundFontEngine.ts', import.meta.url), 'utf8');
const gmName = {};
for (const m of engineSrc.matchAll(/\{\s*id:\s*(\d+),\s*name:\s*'([^']+)'/g)) {
  gmName[Number(m[1])] = m[2];
}

const buf = readFileSync(new URL('../public/midi/placeholder.mid', import.meta.url));
const midi = new Midi(buf);

const ppq = midi.header.ppq || 480;
const ticksPer16th = ppq / 4;
let lastEnd = 0;
midi.tracks.forEach((t) => t.notes.forEach((n) => {
  lastEnd = Math.max(lastEnd, n.ticks + n.durationTicks);
}));
const rawSteps = Math.max(16, Math.ceil(lastEnd / ticksPer16th));
const stepCount = Math.max(16, Math.min(MAX_STEPS, Math.ceil(Math.min(rawSteps, MAX_STEPS) / STEPS_PER_BAR) * STEPS_PER_BAR));

let bpm = 120;
if (midi.header.tempos?.length) {
  const b = Math.round(midi.header.tempos[0].bpm);
  if (b >= 40 && b <= 300) bpm = b;
}

const tracks = [];
const gridSteps = {};
const gm = {};
const presets = {};
const velocity = {};
const selected = [];
const clips = [];

midi.tracks
  .filter((t) => t.notes.length > 0)
  .forEach((t, i) => {
    const gmProg = typeof t.instrument?.number === 'number'
      ? Math.max(0, Math.min(127, t.instrument.number)) : 0;
    const name = (t.name || gmName[gmProg] || `MIDI Track ${i + 1}`).slice(0, 48);
    const id = `sct${i}`;

    const counts = new Map();
    t.notes.forEach((n) => counts.set(n.midi, (counts.get(n.midi) || 0) + 1));
    let rep = 60;
    let best = -1;
    counts.forEach((c, p) => { if (c > best) { best = c; rep = p; } });
    const repName = midiNoteName(Math.max(21, Math.min(108, rep)));
    const avgVel = Math.round(t.notes.reduce((s, n) => s + n.velocity, 0) / t.notes.length * 127);

    tracks.push({
      id, name, category: 'SoundFont Instruments', type: 'soundfont',
      note: repName, color: CHANNEL_COLORS[i % CHANNEL_COLORS.length],
      defaultGmId: gmProg,
    });
    gm[id] = gmProg;
    presets[id] = repName;
    velocity[id] = Math.max(1, Math.min(127, avgVel));
    selected.push(id);

    const q = t.notes
      .map((n, idx) => ({
        step: Math.round(n.ticks / ticksPer16th),
        pitch: Math.max(0, Math.min(127, n.midi)),
        dur: Math.max(1, Math.round(n.durationTicks / ticksPer16th)),
        vel: Math.max(1, Math.min(127, Math.round(n.velocity * 127))),
        idx,
      }))
      .filter((n) => n.step < stepCount)
      .sort((a, b) => a.step - b.step || a.pitch - b.pitch);

    gridSteps[id] = [...new Set(q.map((n) => n.step))].sort((a, b) => a - b);

    const numBlocks = Math.ceil(stepCount / BLOCK_STEPS);
    for (let b = 0; b < numBlocks; b++) {
      const start = b * BLOCK_STEPS;
      const len = Math.min(BLOCK_STEPS, stepCount - start);
      const inBlock = q.filter((n) => n.step >= start && n.step < start + len);
      if (!inBlock.length) continue;
      clips.push({
        id: `sc${i}b${b}`,
        trackId: id,
        name: `${name} · ${b + 1}/${numBlocks}`,
        start,
        length: len,
        notes: inBlock.map((n) => ({
          id: `sn${i}${b}x${n.idx}`,
          pitch: n.pitch,
          start: n.step - start,
          duration: Math.min(n.dur, len - (n.step - start) + 8),
          velocity: n.vel,
        })),
      });
    }
  });

const out = `// AUTO-GENERATED by npm run showcase from public/midi/placeholder.mid — do not edit.
export const SHOWCASE_SONG = ${JSON.stringify(
  { bpm, stepCount, tracks, gridSteps, gm, presets, velocity, selected, clips },
)};
`;

writeFileSync(new URL('../components/ShowcaseSong.ts', import.meta.url), out);
console.log(`showcase: ${tracks.length} tracks, ${clips.length} blocks, ${stepCount} steps (${stepCount / 16} bars), bpm ${bpm}`);
